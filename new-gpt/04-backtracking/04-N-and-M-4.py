# 백준 15652번 — N과 M (4)

# 자연수 N과 M이 주어져.
# 1부터 N까지의 자연수 중에서 M개를 선택하여 다음 조건을 만족하는 모든 수열을 출력해야 해.
# 1. 같은 숫자를 여러 번 선택할 수 있어.
# 2. 수열의 길이는 정확히 M이어야 해.
# 3. 수열은 비내림차순이어야 해.
# 4. 조건을 만족하는 모든 수열을 사전순으로 출력해야 해.
# 입력 범위는 1 ≤ M ≤ N ≤ 8이야.

# 비내림차순이란?
# 숫자가 왼쪽에서 오른쪽으로 갈수록 작아지지 않는 것을 의미해.

# 2 3

# 1 1 1
# 1 1 2
# 1 2 2
# 2 2 2

n, m = map(int, input().split())
path = []

def dfs(x):

  if len(path) == m:
    print(*path)
    return

  for i in range(x, n + 1):
    path.append(i)

    dfs(i)

    path.pop()

dfs(1)

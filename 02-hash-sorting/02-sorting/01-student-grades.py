# 학생 성적 정렬하기

# 학생 정보가 (이름, 국어, 영어) 형태로 주어져.

# 다음 우선순위에 따라 정렬하는 solution(students)를 작성해.
# 1. 국어 점수 내림차순
# 2. 국어가 같으면 영어 점수 오름차순
# 3. 두 점수 모두 같으면 이름 오름차순

# students = [
#     ("민수", 90, 80),
#     ("영희", 85, 95),
#     ("철수", 90, 70),
#     ("지수", 90, 80),
#     ("수빈", 85, 90)
# ]

# [
#   ("철수", 90, 70),
#   ("민수", 90, 80),
#   ("지수", 90, 80),
#   ("수빈", 85, 90),
#   ("영희", 85, 95)
# ]

def solution(students):
    return sorted(students, key=lambda x: (-x[1], x[2], x[0]))
